-- 11. 创建存储过程
-- ============================================================
CREATE OR REPLACE PROCEDURE TEST_SNOWFLAKE_LEANING.SCHM_F_SNOWLEARN_01.SP_LOAD_DIM_ACCOUNT_FROM_GIT()
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS CALLER
AS
BEGIN
  ALTER GIT REPOSITORY Test_Snowflake_Leaning.SCHM_F_SNOWLEARN_01.SNOWFLAKE_LEARNING_REPO FETCH;

  INSERT INTO Test_Snowflake_Leaning.SCHM_F_SNOWLEARN_01.DIM_ACCOUNT (
    ACCOUNT_ID, CLIENT_NAME, RISK_LEVEL, ACCOUNT_TYPE, OPEN_DATE, IS_ACTIVE
  )
  SELECT
    $1 AS ACCOUNT_ID,
    $2 AS CLIENT_NAME,
    $3 AS RISK_LEVEL,
    $4 AS ACCOUNT_TYPE,
    TRY_TO_DATE($5) AS OPEN_DATE,
    TRY_TO_BOOLEAN($6) AS IS_ACTIVE
  FROM @Test_Snowflake_Leaning.SCHM_F_SNOWLEARN_01.SNOWFLAKE_LEARNING_REPO/branches/main/DIM_ACCOUNT.csv
    (FILE_FORMAT => 'Test_Snowflake_Leaning.SCHM_F_SNOWLEARN_01.FF_CSV_HEADER');

  RETURN 'DIM_ACCOUNT loaded successfully at ' || CURRENT_TIMESTAMP()::VARCHAR;
END;

